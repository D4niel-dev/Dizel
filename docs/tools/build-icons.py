"""Generate docs/js/demo-icons.js from the desktop app's icon set.

The desktop app tints its icons by using them as CSS masks. That breaks when the
demo is opened straight from disk (file://), because Chrome will not load an
external .svg as a mask image from a file:// document. So the same glyphs are
inlined here as SVG bodies and drawn with currentColor instead.

Run from the repository root:
    python docs/tools/build-icons.py
"""

from __future__ import annotations

import json
import pathlib
import re

ICONS = [
    "edit-3",
    "new-chat-2",
    "workspace-2",
    "image",
    "layout",
    "search",
    "archive",
    "book",
    "activity",
]

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "desktop" / "public" / "icons"
TARGET = ROOT / "docs" / "js" / "demo-icons.js"

entries = {}

for name in ICONS:
    text = (SOURCE / f"{name}.svg").read_text(encoding="utf-8")
    match = re.search(r"<svg([^>]*)>(.*)</svg>", text, re.S)
    if not match:
        raise SystemExit(f"not an svg: {name}")
    attrs, body = match.group(1), match.group(2)

    view_box = re.search(r'viewBox="([^"]+)"', attrs)
    view_box = re.sub(r"\.0+", "", view_box.group(1)) if view_box else "0 0 24 24"

    filled = 'fill="#000000"' in body
    stroke_width = re.search(r'stroke-width="([^"]+)"', body)
    stroke_width = stroke_width.group(1) if stroke_width else "1.7"

    body = re.sub(r'\s*stroke="#000000"', "", body)
    if filled:
        body = body.replace('fill="#000000"', 'fill="currentColor"')
    else:
        body = re.sub(r'\s*fill="[^"]*"', "", body)

    body = re.sub(r"\s+", " ", body).strip()
    entries[name] = {
        "vb": view_box,
        "sw": stroke_width,
        "fill": filled,
        "body": body,
    }

payload = json.dumps(entries, ensure_ascii=False, indent=2)
TARGET.write_text(
    "/* Generated by docs/tools/build-icons.py — do not edit by hand. */\n"
    f"window.DIZEL_DRAW = {payload};\n",
    encoding="utf-8",
)
print(f"wrote {TARGET.relative_to(ROOT)} ({len(entries)} glyphs)")
