def find_datasets() -> dict:
    """Scan data/formatted/ for dataset files and return {name: path}."""
    base = "data/formatted"
    if not os.path.isdir(base):
        return {}
    datasets = {}
    for f in sorted(os.listdir(base)):
        full = os.path.join(base, f)
        if os.path.isfile(full):
            size_mb = os.path.getsize(full) / (1024 * 1024)
            name = f.replace("v15_", "").replace(".txt", "").replace(".jsonl", "")
            datasets[name] = {"path": full, "size_mb": size_mb}
    return datasets


