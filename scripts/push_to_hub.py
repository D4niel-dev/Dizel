def push_model(api, repo: str, token: str, ckpt_path: str = None, dry_run: bool = False, datasets_repo: str = None, phase: str = "auto", gguf_dir: str = None):
    """Upload model checkpoint(s) + tokenizer + source to HF Hub.

    - phase="auto" (default): upload ALL phases' best checkpoints at once.
    - phase=<name>: upload just that phase's best checkpoint.
    - ckpt_path given: upload just that single checkpoint file.
    - gguf_dir given: also upload *.gguf files from that directory alongside the checkpoints.
    """
    print(f"\n  ── Model Upload: {repo} ──")

    # ── Resolve the list of checkpoints to upload ──────────────────
    if ckpt_path:
        src = find_checkpoint(ckpt_path)
        cp = {"path": src, "phase": classify_phase(os.path.basename(src)),
              "name": os.path.basename(src)}
        ckpts = [cp]
    elif phase != "auto":
        all_b = find_best_checkpoints()
        ckpts = [c for c in all_b if c["phase"] == phase]
        if not ckpts:
            _warn(f"No *-best.pt checkpoint found for phase '{phase}' "
                  f"— falling back to all phases")
            ckpts = all_b
    else:
        ckpts = find_best_checkpoints()

    if not ckpts:
        _warn("No checkpoint to upload.")
        return None, None

    # ── Optional GGUF files ──────────────────────────────────────
    ggufs = []
    if gguf_dir is not None:
        ggufs = find_gguf_files(gguf_dir)
        if not ggufs:
            _warn(f"No .gguf files found in '{gguf_dir}' — skipping GGUF upload")
        else:
            _info(f"GGUF files to upload ({len(ggufs)}):")
            for g in ggufs:
                _info(f"  {g['name']:40s} {g['size_mb']:>7.1f} MB  ({g['quant']})")

    _info(f"Checkpoints to upload ({len(ckpts)}):")
    for c in ckpts:
        vl = f"{c['val_loss']:.4f}" if c.get("val_loss") is not None else "—"
        st = f"step {c.get('step'):,}" if c.get("step") else "step ?"
        _info(f"  [{c['phase']:9s}] {c['name']}  ({st}, val_loss={vl}, {c.get('size_mb', 0):.0f} MB)")

    # ── Shared info from the FIRST checkpoint ──────────────────────
    config = extract_config(ckpts[0]["path"])
    _info(f"Model: {config['d_model']}d × {config['n_layers']} layers, {config['kv_heads']} KV heads")

    # ── Tokenizer ─────────────────────────────────────────────────
    tok_path = find_tokenizer()
    if tok_path:
        _info(f"Tokenizer: {tok_path}")

    # ── Banner ────────────────────────────────────────────────────
    banner_path = find_banner()

    # ── Build files ───────────────────────────────────────────────
    out_dir = tempfile.mkdtemp(prefix="dizel_hub_")

    # Build the uploads log (one entry per checkpoint)
    uploads = []
    for c in ckpts:
        remote = f"dizel-v15-{c['phase']}-best.pt"
        ck = torch.load(c["path"], map_location="cpu", weights_only=False)
        raw_vl = ck.get("val_loss")
        if raw_vl is not None and raw_vl == float("inf"):
            raw_vl = None
        meta = {"step": ck.get("step", 0), "val_loss": raw_vl}
        del ck
        total_mb = os.path.getsize(c["path"]) / (1024 * 1024)
        uploads.append({**c, "remote": remote, "step": meta["step"],
                        "val_loss": meta["val_loss"], "mb": total_mb})
        shutil.copy2(c["path"], os.path.join(out_dir, remote))
        vl = f"{meta['val_loss']:.4f}" if meta["val_loss"] is not None else "—"
        _info(f"[{c['phase']:9s}] {remote}  (step {meta['step']}, val_loss {vl}, {total_mb:.0f} MB)")

    for g in ggufs:
        shutil.copy2(g["path"], os.path.join(out_dir, g["name"]))
        _info(f"[gguf] {g['name']}  ({g['quant']}, {g['size_mb']:.0f} MB)")

    # Shared files — once
    if tok_path:
        shutil.copy2(tok_path, os.path.join(out_dir, "dizel_v15.model"))
    if banner_path:
        shutil.copy2(banner_path, os.path.join(out_dir, "Dizel_banner.png"))

    with open(os.path.join(out_dir, "config.json"), "w") as f:
        json.dump(config, f, indent=2)

    src = os.path.join(os.path.dirname(__file__), "..", "model", "architecture.py")
    if os.path.exists(src):
        shutil.copy2(src, os.path.join(out_dir, "architecture.py"))
        rope_src = os.path.join(os.path.dirname(__file__), "..", "model", "rope.py")
        if os.path.exists(rope_src):
            shutil.copy2(rope_src, os.path.join(out_dir, "rope.py"))

    with open(os.path.join(out_dir, "requirements.txt"), "w") as f:
        f.write(build_requirements())

    readme = build_readme(config, uploads, datasets_repo, phase, ggufs=ggufs)
    with open(os.path.join(out_dir, "README.md"), "w") as f:
        f.write(readme)

    # ── Upload ────────────────────────────────────────────────────
    files = [u["remote"] for u in uploads] + [g["name"] for g in ggufs] + ["dizel_v15.model", "config.json",
             "architecture.py", "rope.py", "requirements.txt",
             "README.md", "Dizel_banner.png"]

    if dry_run:
        _info(f"[DRY RUN] Files ready for {repo}:")
        for f in files:
            p = os.path.join(out_dir, f)
            if os.path.exists(p):
                _info(f"  {f} ({os.path.getsize(p)/1024/1024:.0f} MB)")
        shutil.rmtree(out_dir, ignore_errors=True)
        return None, None

    from huggingface_hub import create_repo
    create_repo(repo, exist_ok=True, private=False, token=token)
    _ok(f"Repo ready: {repo}")

    for fname in files:
        local_path = os.path.join(out_dir, fname)
        if not os.path.exists(local_path):
            continue
        size_mb = os.path.getsize(local_path) / (1024 * 1024)
        print(f"    Uploading {fname} ({size_mb:.0f} MB)...")
        api.upload_file(path_or_fileobj=local_path, path_in_repo=fname,
                        repo_id=repo, token=token)
        _ok(f"{fname}")

    shutil.rmtree(out_dir, ignore_errors=True)
    _info(f"https://huggingface.co/{repo}")
    return repo, uploads


def push_gguf_only(api, repo: str, token: str, gguf_dir: str, dry_run: bool = False):
    """Upload *.gguf files to a repo (model repo, or a dedicated GGUF repo)."""
    print(f"\n  ── GGUF Upload: {repo} ──")
    ggufs = find_gguf_files(gguf_dir)
