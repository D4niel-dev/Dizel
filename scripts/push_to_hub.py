# Push Dataset
# ═══════════════════════════════════════════════════════════════════

def push_dataset(api, repo: str, token: str, selected: list[str] = None, dry_run: bool = False):
    """Upload dataset files to HF Hub datasets repo."""
    print(f"\n  ── Dataset Upload: {repo} ──")

    available = find_datasets()
    if not available:
        _warn("No dataset files found in data/formatted/")
        _info("Run Phase A first to generate datasets.")
        return

    _info("Available datasets:")
    for name, info in available.items():
        _info(f"  {name:25s}  {info['size_mb']:>7.1f} MB  ({info['path']})")

    if selected is None:
        selected = list(available.keys())
    elif isinstance(selected, str):
        selected = [s.strip() for s in selected.split(",") if s.strip()]

    # Filter to only available
    to_upload = [s for s in selected if s in available]
    if not to_upload:
        _warn("None of the selected datasets are available.")
        return

    # Also include tokenizer
    tok_path = find_tokenizer()

    # Build files
    out_dir = tempfile.mkdtemp(prefix="dizel_dataset_")
    uploaded = []

    for name in to_upload:
        src = available[name]["path"]
        dst = os.path.basename(src)  # keep original filename
        shutil.copy2(src, os.path.join(out_dir, dst))
        size_mb = available[name]["size_mb"]
        kind = "pretrain text" if dst.endswith(".txt") else "conversations"
        uploaded.append((dst, size_mb, kind))
        _info(f"Prepared: {dst} ({size_mb:.0f} MB)")

    # Copy tokenizer alongside
    if tok_path:
        shutil.copy2(tok_path, os.path.join(out_dir, os.path.basename(tok_path)))
        _info(f"Prepared: {os.path.basename(tok_path)}")

    # README
    readme = build_dataset_readme(uploaded, os.path.basename(tok_path) if tok_path else None)
    with open(os.path.join(out_dir, "README.md"), "w") as f:
        f.write(readme)
    _info("Prepared: README.md")

    total_mb = sum(s for _, s, _ in uploaded)

    if dry_run:
        _info(f"[DRY RUN] Files ready for {repo}:")
        for name, size, kind in uploaded:
            _info(f"  {name} ({size:.0f} MB, {kind})")
        _info(f"  README.md")
        if tok_path:
            _info(f"  {os.path.basename(tok_path)}")
        _info(f"  Total: {total_mb:.0f} MB")
        shutil.rmtree(out_dir, ignore_errors=True)
        return

    # Confirm upload
    print(f"\n  About to upload {len(uploaded)} files ({total_mb:.0f} MB total) to {repo}")
    if not _confirm("  Proceed?"):
        _info("Cancelled.")
        shutil.rmtree(out_dir, ignore_errors=True)
        return

    from huggingface_hub import create_repo

    create_repo(repo, exist_ok=True, private=False, token=token,
                repo_type="dataset")
    _ok(f"Dataset repo: {repo}")

    for name, size_mb, _ in uploaded:
        local = os.path.join(out_dir, name)
        print(f"    Uploading {name} ({size_mb:.0f} MB)...")
        api.upload_file(path_or_fileobj=local, path_in_repo=name,
                        repo_id=repo, token=token, repo_type="dataset")
        _ok(f"{name}")

    # Upload tokenizer
    if tok_path:
        tok_name = os.path.basename(tok_path)
        api.upload_file(path_or_fileobj=os.path.join(out_dir, tok_name),
                        path_in_repo=tok_name, repo_id=repo, token=token,
                        repo_type="dataset")
        _ok(f"{tok_name}")

    # Upload README
    api.upload_file(path_or_fileobj=os.path.join(out_dir, "README.md"),
                    path_in_repo="README.md", repo_id=repo, token=token,
                    repo_type="dataset")
    _ok(f"README.md")

    shutil.rmtree(out_dir, ignore_errors=True)
    _info(f"https://huggingface.co/datasets/{repo}")


