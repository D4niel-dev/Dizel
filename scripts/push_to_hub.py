def _info(msg): print(f"  {msg}")
def _ok(msg):   print(f"  ✓ {msg}")
def _warn(msg): print(f"  ⚠ {msg}")
def _ask(prompt, default=None):
    """Ask the user a question and return the answer."""
    if default:
        return input(f"  {prompt} [{default}]: ").strip() or default
    return input(f"  {prompt}: ").strip()

def _confirm(prompt, default=True):
    """Ask yes/no."""
    hint = "Y/n" if default else "y/N"
    answer = input(f"  {prompt} [{hint}]: ").strip().lower()
    if not answer:
        return default
    return answer.startswith("y")


# Phases in training order; used to classify checkpoint filenames.
PHASE_ORDER = ["pretrain", "sft", "distill", "dpo"]
# Filenames containing any of these substrings are treated as legacy/stale
# and excluded from best-checkpoint discovery (e.g. dizel-lite-best.pt).
EXCLUDE_SUBSTRINGS = ("lite", "old", "backup", "stale")
PHASE_LABELS = {
    "pretrain": "Phase A — Pretrain",
    "sft":      "Phase B — SFT",
    "distill":  "Phase C — Distillation",
    "dpo":      "Phase D — DPO",
}

def classify_phase(filename: str) -> str:
    """Infer the training phase from a checkpoint filename like
    dizel-v15-sft-best.pt -> 'sft'. Returns 'pretrain' if unknown."""
    name = filename.lower()
    for p in PHASE_ORDER:
        if p in name:
            return p
    return "pretrain"  # safe default


def _gguf_quant(filename: str) -> str:
    """Best-effort quantization tag from a GGUF filename (Q4_K_M, Q8_0, F16, ...)."""
    m = re.search(r"(q[0-9]_[a-z0-9_]+|f16|bf16|f32)", filename.lower())
    return m.group(1).upper() if m else "unknown"


def find_gguf_files(source_dir: str = "checkpoints") -> list:
    """Scan a directory for *.gguf files.

    Returns list of dicts {path, name, size_mb, quant}, sorted by name.
    Warns if a file named exactly 'Dizel.gguf' is found (the known-bad
    59-tensor artifact from the pre-fix converter).
    """
    result = []
    if not os.path.isdir(source_dir):
        _warn(f"GGUF source dir not found: {source_dir}")
        return result
    for f in sorted(os.listdir(source_dir)):
        if not f.lower().endswith(".gguf"):
            continue
        full = os.path.join(source_dir, f)
        if not os.path.isfile(full):
            continue
        if f == "Dizel.gguf":
            _warn(f"'{f}' matches the known-bad 59-tensor artifact — verify it was "
                  f"regenerated by the fixed converter before uploading.")
        result.append({
            "path": full,
            "name": f,
            "size_mb": os.path.getsize(full) / (1024 * 1024),
            "quant": _gguf_quant(f),
        })
    return result


