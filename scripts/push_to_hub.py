def main():
    parser = argparse.ArgumentParser(description="Upload Dizel v1.5 to Hugging Face Hub")
    parser.add_argument("--model", action="store_true", help="Push model checkpoint")
    parser.add_argument("--dataset", action="store_true", help="Push dataset files")
    parser.add_argument("--all", action="store_true", help="Push model + dataset")
    parser.add_argument("--repo", default=None, help="Target repo (auto-selected per mode)")
    parser.add_argument("--token", default=None, help="HF token (or HF_TOKEN env var)")
    parser.add_argument("--checkpoint", default=None, help="Specific checkpoint file")
    parser.add_argument("--phase", default="auto",
                        choices=["auto", "all", "pretrain", "sft", "distill", "dpo"],
                        help="Which phase's best checkpoint to upload (default: auto; 'all' is an alias for 'auto')")
    parser.add_argument("--datasets", default=None,
                        help="Comma-separated datasets to upload (e.g. 'pretrain,sft,distill')")
    parser.add_argument("--gguf", action="store_true",
                        help="Also upload GGUF files (with --model) or push GGUF files only")
    parser.add_argument("--gguf-dir", default=None,
                        help="Directory containing *.gguf files (default: checkpoints/) — "
                             "use a Drive path for Colab artifacts")
    parser.add_argument("--gguf-repo", default=None,
                        help="Dedicated repo for GGUF uploads (default: same as model repo)")
    parser.add_argument("--dry-run", action="store_true", help="Prepare files without uploading")
    args = parser.parse_args()

    # 'all' is a user-friendly alias for 'auto' (uploads every phase's best).
    if args.phase == "all":
        args.phase = "auto"

    token = args.token or os.environ.get("HF_TOKEN")
    if not token and not args.dry_run:
        print("Error: No HF token. Set HF_TOKEN env var or pass --token")
        sys.exit(1)

    from huggingface_hub import HfApi
    api = HfApi(token=token) if not args.dry_run else None

    # ── Determine mode ────────────────────────────────────────────
    mode = None
    model_repo = "D4niel-dev/Dizel-1.5"
    datasets_repo = "D4niel-dev/Dizel-Datasets"
    gguf_repo = None

    if args.model:
        mode = "model"
    elif args.dataset:
        mode = "dataset"
    elif args.all:
        mode = "both"
    elif args.gguf:
        mode = "gguf"
    else:
        # Interactive
        print()
        print("  ── Dizel Hub Upload ──")
        choice = _ask("What to push? (model / dataset / both / gguf)", "model")
        if choice == "dataset":
            mode = "dataset"
        elif choice == "both":
            mode = "both"
        elif choice == "gguf":
            mode = "gguf"
        else:
            mode = "model"

        if not args.repo:
            if mode == "dataset":
                mr = _ask(f"Dataset repo", datasets_repo)
                if mr: datasets_repo = mr
            elif mode == "model":
                mr = _ask(f"Model repo", model_repo)
                if mr: model_repo = mr
            elif mode == "gguf":
                mr = _ask(f"GGUF repo", model_repo)
                if mr: gguf_repo = mr
            elif mode == "both":
                mr = _ask(f"Model repo", model_repo)
                if mr: model_repo = mr
                dr = _ask(f"Dataset repo", datasets_repo)
                if dr: datasets_repo = dr

    # Override repos from CLI if provided
    if args.repo:
        if mode == "dataset" or mode == "both":
            datasets_repo = args.repo
        else:
            model_repo = args.repo

    # ── Execute ───────────────────────────────────────────────────
    if mode == "model":
        gguf_dir = args.gguf_dir if args.gguf else None
        push_model(api, model_repo, token, args.checkpoint, args.dry_run, datasets_repo, phase=args.phase, gguf_dir=gguf_dir)

    elif mode == "gguf":
        gguf_repo = args.gguf_repo or gguf_repo or model_repo
        push_gguf_only(api, gguf_repo, token, args.gguf_dir or "checkpoints", args.dry_run)

    elif mode == "dataset":
        selected = args.datasets.split(",") if args.datasets else None
        push_dataset(api, datasets_repo, token, selected, args.dry_run)

    elif mode == "both":
        push_model(api, model_repo, token, args.checkpoint, args.dry_run, datasets_repo, phase=args.phase, gguf_dir=args.gguf_dir if args.gguf else None)
        print()
        selected = args.datasets.split(",") if args.datasets else None
        push_dataset(api, datasets_repo, token, selected, args.dry_run)

    if args.dry_run:
        _info("[DRY RUN] No files uploaded.")
    else:
        print(f"\n{'='*60}")
        _ok("Upload complete!")
        print(f"{'='*60}")


if __name__ == "__main__":
    main()