    out_dir = tempfile.mkdtemp(prefix="dizel_gguf_")
    with open(os.path.join(out_dir, "README.md"), "w") as f:
        f.write(build_gguf_readme(ggufs, config))

    if dry_run:
        _info("[DRY RUN] Files ready for %s:" % repo)
        for g in ggufs:
            _info(f"  {g['name']} ({g['size_mb']:.0f} MB, {g['quant']})")
        _info("  README.md")
        shutil.rmtree(out_dir, ignore_errors=True)
